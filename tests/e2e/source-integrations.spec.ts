import {test,expect} from "@playwright/test";
import {ensureE2eRateLimits} from "./support/rate-limits";
test("generated session example saves, resumes and finalizes; only Session examples are available",async({page},testInfo)=>{
 await page.goto('/login');await page.getByLabel('Username').fill('forman');await page.getByLabel('Password',{exact:true}).fill('forman-e2e-password-2026');await page.getByRole('button',{name:'Login',exact:true}).click();await expect(page).toHaveURL('/app');await ensureE2eRateLimits(page);
 const headers={origin:'http://localhost:3100'};
 const source=await (await page.request.post('/api/admin/v1/sources',{headers,data:{name:`Integration ${testInfo.project.name}`,type:"session"}})).json();
 const path=`/api/admin/v1/sources/${source.sourceId}`;
 expect((await page.request.patch(path,{headers,data:{section:'source-fields',values:{fieldDefinitionMode:'json-schema',fieldDefinitionSource:JSON.stringify({type:'object',properties:{answer:{type:'string',minLength:2},score:{type:'number',minimum:1,maximum:5}},required:['answer'],additionalProperties:false})}}})).ok()).toBe(true);
 expect((await page.request.patch(path,{headers,data:{section:'protection',values:{altchaEnabled:false,honeypotEnabled:true}}})).ok()).toBe(true);
 const {integration}=await (await page.request.get(path)).json();
 expect(integration.sourceType).toBe("session");expect(integration.browserJavaScript).toBe("");expect(integration.m2mCurl).toBe("");
 await page.goto(`/app/sources/${source.sourceId}`);await page.getByRole('tab',{name:"Integration",exact:true}).click();
 await expect(page.getByRole('combobox',{name:'Example',exact:true})).toBeVisible();
 await page.screenshot({path:testInfo.outputPath('integrations.png'),fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.route('**/integration-example',route=>route.fulfill({contentType:'text/html',body:integration.sessionJavaScript}));
 await page.goto('/integration-example');
 await page.getByLabel('answer',{exact:true}).fill('First answer');
 await page.getByRole('button',{name:'Next',exact:true}).click();
 await expect(page.getByLabel('answer',{exact:true})).toBeHidden();
 await page.getByLabel('score',{exact:true}).fill('3');
 await page.getByRole('button',{name:'Save draft'}).click();
 await expect(page.getByRole('status')).toContainText('Draft saved');
 expect(new URL(page.url()).hash).toMatch(/^#session=/);
 await page.reload();
 await expect(page.getByLabel('answer',{exact:true})).toHaveValue('First answer');
 await expect(page.getByLabel('score',{exact:true})).toBeVisible();
 await expect(page.getByLabel('score',{exact:true})).toHaveValue('3');
 await page.getByRole('button',{name:'Submit',exact:true}).click();
 await expect(page.getByRole('status')).toHaveText('Response submitted.');
 await page.reload();await expect(page.getByRole('status')).toHaveText('Response submitted.');
 await expect(page.getByRole('button',{name:'Submit',exact:true})).toBeDisabled();
});
