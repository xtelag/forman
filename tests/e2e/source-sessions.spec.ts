import { randomBytes } from "node:crypto";
import { expect, test } from "@playwright/test";
import { openFilters } from "./support/filter-panel";
import { ensureE2eRateLimits } from "./support/rate-limits";

test("administrator creates a Session Source and reviews a resumed, finalized form", async ({ page, request }, testInfo) => {
  await page.goto("/login");
  await page.getByLabel("Username").fill("forman");
  await page.getByLabel("Password", { exact: true }).fill("forman-e2e-password-2026");
  await page.getByRole("button", { name: "Login", exact: true }).click();
  await expect(page).toHaveURL("/app");
  await ensureE2eRateLimits(page);
  await page.goto("/app/sources");
  await page.getByRole("button", { name: "Create Source", exact: true }).click();
  await page.getByRole("textbox", { name: "Name", exact: true }).fill(`Session ${testInfo.project.name}`);
  await page.getByRole("radio", { name: "Session", exact: true }).check();
  await page.getByRole("dialog", { name: "Create Source", exact: true }).getByRole("button", { name: "Create Source", exact: true }).click();
  await expect(page).toHaveURL(/\/app\/sources\/[a-z0-9]+$/);
  const sourceId = new URL(page.url()).pathname.split("/").at(-1)!;
  await page.getByRole("tab", { name: "Protection", exact: true }).click();
  await expect(page.getByRole("checkbox", { name: "Enable ALTCHA", exact: true })).toBeChecked();
  await expect(page.getByRole("checkbox", { name: "Enable honeypot", exact: true })).not.toBeChecked();
  await page.getByRole("checkbox", { name: "Enable ALTCHA", exact: true }).uncheck();
  await page.getByRole("button", { name: "Save protection", exact: true }).click();
  await expect(page.getByRole("button", { name: "Save protection", exact: true })).toBeDisabled();
  const key = randomBytes(32).toString("base64url");
  const api = `/api/submit/${sourceId}`;
  const headers = {};
  expect((await request.post(api, { headers, data: { sessionId: key, operation: "open" } })).status()).toBe(201);
  const update = { sessionId: key, operation: "update", operationId: "first-save-123456", revision: 0, payload: { answer: "Part one" } };
  expect((await request.post(api, { headers, data: update })).status()).toBe(200);
  const resume = await request.post(api, { headers, data: { sessionId: key, operation: "open" } });
  expect((await resume.json()).payload).toEqual({ answer: "Part one" });
  await expect(page.getByRole("link", { name: "View sessions" })).toHaveCount(0);
  await page.goto("/app/submissions");
  await openFilters(page);
  await page.getByLabel("Source", { exact: true }).selectOption({ label: `Session ${testInfo.project.name}` });
  await page.getByLabel("Type", { exact: true }).selectOption("session");
  await page.getByLabel("State", { exact: true }).selectOption("draft");
  await page.getByRole("button", { name: "Apply filters", exact: true }).click();
  await expect(page).toHaveURL(/type=session.*state=draft/);
  const draftLink = page.getByRole("row").filter({ hasText: `Session ${testInfo.project.name}` }).first();
  await draftLink.click();
  await expect(page.getByRole("heading", { name: "Submission", exact: true })).toBeVisible();
  await expect(page.locator('[data-slot="resource-section"]', { hasText: "Data" })).toContainText("Part one");
  await page.getByRole("button", { name: "Submission actions" }).click();
  await expect(page.getByRole("menuitem", { name: "Delete permanently", exact: true })).toBeDisabled();
  await page.keyboard.press("Escape");
  const final = { ...update, operationId: "final-save-123456", revision: 1, final: true, payload: { answer: "Completed answer" } };
  const finished = await (await request.post(api, { headers, data: final })).json();
  expect(finished.status).toBe("completed");
  const repeated = await (await request.post(api, { headers, data: final })).json();
  expect(repeated.submissionId).toBe(finished.submissionId);
  await page.goto("/app/submissions?type=session&state=completed");
  await expect(page.getByRole("heading", { name: "Submissions", exact: true })).toBeVisible();
  const link = page.getByRole("row").filter({ hasText: `Session ${testInfo.project.name}` }).first();
  await link.click();
  await expect(page.locator('[data-slot="resource-section"]', { hasText: "Data" })).toContainText("Completed answer");
  await expect(page.getByText("Session updates: 2", { exact: true })).toBeVisible();
  await expect(page.getByText("Session requests: 4", { exact: true })).toBeVisible();
});
